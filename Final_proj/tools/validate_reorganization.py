#!/usr/bin/env python3
"""Inventory the curated algorithm-first project without loading ML libraries.

The default command is read-only.  --write explicitly writes only the generated
catalog and validation receipt.  All paths in those files are package-relative.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path, PurePosixPath
import posixpath
import re
from urllib.parse import unquote, urlsplit

CURATED_DIRECTORIES = ('SPRING', 'VMC', 'MinSR', 'SA', 'shared', 'benchmarks', 'documents', 'tools', 'validation')
REQUIRED_DIRECTORIES = ('SPRING', 'VMC', 'MinSR', 'SA', 'shared', 'benchmarks', 'documents', 'tools')
ROOT_DOCUMENTS = ('README.md', 'AGENTS.md', 'MIGRATION.md', 'SUBMISSION.md', 'THIRD_PARTY.md',
                  'BUILD_REPORTS.txt', 'requirements.txt', 'requirements-cpu.txt',
                  'requirements-gpu.txt', 'pyproject.toml', 'uv.lock', '.python-version',
                  '.gitignore', '.gitattributes')
GENERATED = ('SOURCE_CATALOG.json', 'validation/reorganization_validation.json')
LEGACY_ROOTS = ('SPRING_Haldane_FQHE', 'SPRING_Ising_test')
MAX_FILE_BYTES = 50_000_000  # Refuse >=50 MB; small NPZ reference data remain eligible.
CACHE_NAMES = {'.git', '.hg', '.svn', '__pycache__', '.pytest_cache', '.ruff_cache', '.mypy_cache',
               '.cache', '.ipynb_checkpoints', 'build', 'dist', 'node_modules', 'venv'}
PRIVATE_NAMES = {'.aws', '.ssh', '.gnupg', '.codex', '.agents', '.tacc_ssh', 'secrets', 'credentials'}
TEXT_SUFFIXES = {'.py', '.sh', '.md', '.rst', '.txt', '.json', '.toml', '.yaml', '.yml', '.tex',
                '.cfg', '.ini', '.csv', '.slurm', '.sbatch'}
TOKEN_PATTERNS = (
    ('private-key header', re.compile(rb'-----BEGIN (?:RSA |EC |DSA |OPENSSH )?PRIVATE KEY-----')),
    ('GitHub token', re.compile(rb'(?:gh[pousr]_[A-Za-z0-9]{30,}|github_pat_[A-Za-z0-9_]{50,})')),
    ('AWS access-key ID', re.compile(rb'(?<![A-Z0-9])(?:AKIA|ASIA)[A-Z0-9]{16}(?![A-Z0-9])')),
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open('rb') as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b''):
            digest.update(chunk)
    return digest.hexdigest()


def json_bytes(value) -> bytes:
    return (json.dumps(value, indent=2, sort_keys=True, ensure_ascii=False, allow_nan=False) + '\n').encode()


def atomic_write(path: Path, content: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name('.' + path.name + '.tmp')
    with temporary.open('xb') as stream:
        stream.write(content)
    temporary.replace(path)


def _cache(name: str) -> bool:
    return name in CACHE_NAMES or name.startswith(('.venv', '.jax_cache', 'jax_cache')) or name.endswith('.egg-info')


def _private(path: PurePosixPath) -> bool:
    name = path.name.lower()
    return (any(part.lower() in PRIVATE_NAMES for part in path.parts)
            or name == '.env' or name.startswith('.env.')
            or name in {'.netrc', '.pypirc', 'id_rsa', 'id_ed25519', 'id_ecdsa',
                        'credentials', 'credentials.json', 'credentials.yaml', 'credentials.yml',
                        'secrets.json', 'secrets.yaml', 'secrets.yml', 'service_account.json', 'service-account.json'}
            or name.endswith(('.pem', '.p12', '.pfx', '.key', '.kdbx')))


def collect(source: Path) -> dict:
    """Return eligible files and issues; never follow a symlink or alter a file."""
    source = source.resolve()
    records, excluded, errors = {}, [], []
    for name in REQUIRED_DIRECTORIES:
        if not (source / name).is_dir() or (source / name).is_symlink():
            errors.append({'path': name, 'reason': 'required curated directory is missing or a symlink'})
    for name in ('README.md', 'SUBMISSION.md', 'THIRD_PARTY.md', 'MIGRATION.md'):
        if not (source / name).is_file():
            errors.append({'path': name, 'reason': 'required current document is missing'})

    def accept(path):
        relative = path.relative_to(source).as_posix()
        if relative in GENERATED:
            return
        if path.is_symlink():
            excluded.append({'path': relative, 'reason': 'symlink file is never exported'})
            return
        if _private(PurePosixPath(relative)):
            errors.append({'path': relative, 'reason': 'secret/private path is not exportable'})
            return
        if path.suffix in ('.pyc', '.pyo') or path.name.endswith(('~', '.swp', '.swo')):
            excluded.append({'path': relative, 'reason': 'generated bytecode/editor file'})
            return
        size = path.stat().st_size
        if size >= MAX_FILE_BYTES:
            errors.append({'path': relative, 'reason': 'file is >=50 MB; curate it outside Git', 'bytes': size})
            return
        if path.suffix.lower() in TEXT_SUFFIXES:
            content = path.read_bytes()
            for label, pattern in TOKEN_PATTERNS:
                match = pattern.search(content)
                if match:
                    errors.append({'path': relative, 'reason': 'possible ' + label,
                                   'line': content[:match.start()].count(b'\n') + 1})
        records[relative] = {'bytes': size, 'sha256': sha256(path)}

    for name in ROOT_DOCUMENTS:
        path = source / name
        if path.is_file() or path.is_symlink():
            accept(path)
    for name in CURATED_DIRECTORIES:
        top = source / name
        if top.is_symlink():
            excluded.append({'path': name, 'reason': 'symlink directory is never followed'})
            continue
        if not top.is_dir():
            continue
        for folder, directories, files in os.walk(top, followlinks=False):
            folder = Path(folder)
            keep = []
            for child in sorted(directories):
                path = folder / child
                relative = path.relative_to(source).as_posix()
                parts = PurePosixPath(relative).parts
                fresh_run = any(parts[i:i+2] == ('results', 'runs') for i in range(len(parts)-1))
                if fresh_run:
                    excluded.append({'path': relative, 'reason': 'fresh results/runs output; curated fixed evidence remains eligible'})
                elif path.is_symlink() or _cache(child):
                    excluded.append({'path': relative, 'reason': 'symlink directory' if path.is_symlink() else 'cache/environment directory'})
                elif child.lower() in PRIVATE_NAMES:
                    errors.append({'path': relative, 'reason': 'private directory is not exportable'})
                else:
                    keep.append(child)
            directories[:] = keep
            for child in sorted(files):
                accept(folder / child)
    for name in LEGACY_ROOTS:
        if (source / name).exists():
            excluded.append({'path': name, 'reason': 'legacy research tree retained locally, never recursively exported'})
    return {'files': dict(sorted(records.items())), 'excluded': excluded, 'errors': errors}


def _markdown_destinations(text: str):
    """Read inline/reference/HTML links, ignoring fenced code blocks."""
    visible, fence = [], None
    for line in text.splitlines():
        marker = re.match(r'^\s{0,3}(`{3,}|~{3,})', line)
        if marker:
            token = marker.group(1)
            if fence is None:
                fence = token
            elif token[0] == fence[0] and len(token) >= len(fence):
                fence = None
            continue
        if fence is None:
            visible.append(line)
    text = '\n'.join(visible)
    for match in re.finditer(r'\]\(', text):
        start, depth, angle, escaped = match.end(), 1, False, False
        for end in range(start, len(text)):
            char = text[end]
            if escaped:
                escaped = False
                continue
            if char == '\\':
                escaped = True
            elif char == '<':
                angle = True
            elif char == '>':
                angle = False
            elif not angle and char == '(':
                depth += 1
            elif not angle and char == ')':
                depth -= 1
                if depth == 0:
                    raw = text[start:end].strip()
                    if raw.startswith('<'):
                        yield raw[1:raw.find('>')]
                    else:
                        yield re.split(r'\s+[\"\x27]', raw, maxsplit=1)[0]
                    break
            elif char == '\n':
                break
    for match in re.finditer(r'^\s{0,3}\[[^\]]+\]:\s*(<[^>]+>|\S+)', text, re.MULTILINE):
        yield match.group(1).strip('<>')
    for match in re.finditer(r'<(?:a|img)\b[^>]*(?:href|src)\s*=\s*([\"\x27])(.*?)\1', text, re.IGNORECASE):
        yield match.group(2)


def current_navigation(relative: str) -> bool:
    if '/' not in relative:
        return relative.endswith('.md')
    return (relative.startswith(('SPRING/', 'VMC/', 'MinSR/', 'SA/', 'tools/'))
            or relative in ('shared/README.md', 'benchmarks/README.md',
                            'benchmarks/ising/README.md', 'benchmarks/fqhe/README.md'))


def check_links(source: Path, files: dict, legacy_index='MIGRATION.md') -> dict:
    """Check exported paths, not existence in the unpublished local legacy tree."""
    legacy = PurePosixPath(legacy_index)
    if legacy.is_absolute() or '..' in legacy.parts or legacy.suffix.lower() != '.md':
        raise ValueError('The sole legacy-index exception must name one package-relative Markdown file')
    available = set(files) | set(GENERATED)
    directories = {str(PurePosixPath(p).parent) for p in available}
    for path in tuple(directories):
        directories.update(str(parent) for parent in PurePosixPath(path).parents)
    errors, historical, permitted, checked = [], [], [], 0
    for relative in sorted(files):
        if not relative.endswith('.md'):
            continue
        text = (source / relative).read_text(errors='replace')
        for target in _markdown_destinations(text):
            if not target or target.startswith('#') or urlsplit(target).scheme or target.startswith('//'):
                continue
            checked += 1
            path = unquote(target.split('#', 1)[0].split('?', 1)[0]).replace('\\ ', ' ')
            if path.startswith('/Final_proj/'):
                normalized = posixpath.normpath(path[len('/Final_proj/'):])
            elif path.startswith('/') or '\\' in path:
                normalized = None
            else:
                normalized = posixpath.normpath(str(PurePosixPath(relative).parent / path))
            exists = normalized in available or normalized in directories
            if exists:
                continue
            finding = {'document': relative, 'target': target, 'exported_path': normalized}
            archive_target = any(part in (*LEGACY_ROOTS, '_project_archive', '_tacc_archive', '_tacc_results')
                                 for part in PurePosixPath(normalized or path).parts)
            if relative == legacy.as_posix() and archive_target:
                permitted.append(finding)
            elif current_navigation(relative):
                errors.append(finding)
            else:
                historical.append(finding)
    return {'checked_local_paths': checked, 'errors': errors, 'permitted_archive_index_links': permitted,
            'historical_unresolved_links': historical,
            'historical_scope': 'Frozen snapshot/vendor/ED/report-source documents are preserved, not rewritten as current launch instructions',
            'network_links_checked': False, 'Markdown_anchor_fragments_checked': False}


def build_metadata(source: Path, legacy_index='MIGRATION.md') -> tuple[dict, dict, dict]:
    inventory = collect(source)
    links = check_links(source, inventory['files'], legacy_index)
    errors = inventory['errors'] + [{'path': q['document'], 'reason': 'broken current navigation link',
                                    'target': q['target']} for q in links['errors']]
    catalog = {'schema_version': 1, 'path_convention': 'All file paths are relative to Final_proj',
        'included_roots': list(CURATED_DIRECTORIES), 'legacy_roots_not_exported': list(LEGACY_ROOTS),
        'generated_files_excluded_to_avoid_hash_cycles': list(GENERATED),
        'file_count': len(inventory['files']), 'bytes': sum(q['bytes'] for q in inventory['files'].values()),
        'files': inventory['files']}
    report = {'status': 'passed' if not errors else 'failed', 'schema_version': 1,
        'curated_files': len(inventory['files']), 'curated_bytes': catalog['bytes'],
        'max_file_bytes_exclusive': MAX_FILE_BYTES, 'small_NPZ_reference_files_permitted': True,
        'symlinks_never_followed_or_exported': True, 'secret_scan_scope': 'forbidden paths plus private-key/GitHub-token/AWS-ID patterns in known text files',
        'legacy_index': legacy_index, 'errors': errors, 'excluded_paths': inventory['excluded'],
        'links': links, 'SOURCE_CATALOG_sha256': hashlib.sha256(json_bytes(catalog)).hexdigest(),
        'no_network_training_NN_MC_or_Git_mutations': True}
    return inventory, catalog, report


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument('--legacy-index', default='MIGRATION.md')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--check', '--dry-run', action='store_true', help='Read-only validation (the default)')
    mode.add_argument('--write', action='store_true', help='Explicitly write the two generated metadata files only')
    parser.add_argument('--json', action='store_true', help='Print the complete validation report')
    args = parser.parse_args()
    _, catalog, report = build_metadata(args.source.resolve(), args.legacy_index)
    if args.write:
        if report['errors']:
            raise SystemExit('Refusing metadata writes: curated validation failed')
        atomic_write(args.source / GENERATED[0], json_bytes(catalog))
        atomic_write(args.source / GENERATED[1], json_bytes(report))
    output = report if args.json else {k: report[k] for k in ('status', 'curated_files', 'curated_bytes', 'errors')}
    print(json.dumps(output, indent=2))
    raise SystemExit(0 if not report['errors'] else 1)


if __name__ == '__main__':
    main()
